// node tools/coverage.mjs  — writes docs/coverage.md (move / ability / item coverage counts) from the live engine tables.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { getSpec, ABILITY_IMPL, ITEM_IMPL } from "../js/engine.js";
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const L = (n) => JSON.parse(readFileSync(path.join(root, "data", n), "utf8"));
const moves = L("moves.json").filter((m) => m.name !== "Struggle"), items = L("items.json"), abilities = L("abilities.json"), species = L("species.json");
const partial = moves.filter((m) => getSpec(m).partial);
const noop = moves.filter((m) => getSpec(m).noop && !getSpec(m).partial);
const full = moves.length - partial.length;
const abilKeys = Object.keys(abilities);
const used = new Set(species.flatMap((s) => [...s.abilities, ...(s.hidden ? [s.hidden] : [])]));
const usedList = [...used].sort();
const abilImplUsed = usedList.filter((a) => ABILITY_IMPL.has(a));
const abilNoUsed = usedList.filter((a) => !ABILITY_IMPL.has(a));
const itemImpl = items.filter((i) => ITEM_IMPL.has(i.name)), itemNo = items.filter((i) => !ITEM_IMPL.has(i.name));
const md = `# Coverage of the battle simulator

Generated by \`node tools/coverage.mjs\` from the live engine tables (js/engine.js). Do not edit by hand.

## Moves (${moves.length} moves in data/moves.json)

| | count |
|---|---|
| Fully simulated (damage + the effect described by effect_short) | ${full} |
| Partial (damage still applies, the extra effect is not simulated; marked "~" in the UI) | ${partial.length} |
| of which: simulated as "does nothing" by design (no meaning in a 1v1 trainer battle) | ${noop.length} |

### Partial moves
${partial.map((m) => `- **${m.name}** — ${getSpec(m).note} _(effect_short: ${m.effect.trim()})_`).join("\n") || "- none"}

### Implemented effect families
stat-stage changes (self / target / secondary chance), status (burn, poison, toxic, paralysis, sleep 1-3 turns, freeze, confusion), secondary status and flinch chances, recoil (1/4, 1/3, crash), drain (incl. Dream Eater), multi-hit (2, 2-5, Skill Link), fixed damage (level, 20, 40, half HP, Psywave), OHKO moves (30% + level difference), recharge (Hyper Beam), two-turn charge (Solar Beam, Razor Wind, Sky Attack, Skull Bash with its Defense boost), semi-invulnerable Fly / Dig (hit by Gust / Twister / Earthquake), bind, Thrash / Petal Dance lock + confusion, recovery (Recover, Softboiled, Rest), Leech Seed, Reflect / Light Screen (5 turns, 8 with Light Clay), Haze, Mist, Focus Energy, Substitute, Metronome, Mirror Move, Counter, Rage, Self-Destruct / Explosion, high-crit moves, priority (Quick Attack, Counter -5).
There is no Protect-style move among the 151-species dataset (no Gen 2+ moves), so protect is not exercised.

## Abilities (${abilKeys.length} in data/abilities.json; ${usedList.length} appear on the 151 species)

| | count |
|---|---|
| Simulated and used by at least one species | ${abilImplUsed.length} |
| Used by a species but "no effect in sim" (marked in the picker) | ${abilNoUsed.length} |
| Simulated (engine table, includes ones no species has) | ${ABILITY_IMPL.size} |

Simulated and used: ${abilImplUsed.join(", ")}.

No effect in sim (weather, switching, doubles, field or out-of-battle abilities): ${abilNoUsed.join(", ")}.

## Held items (${items.length} in data/items.json)

| | count |
|---|---|
| Simulated | ${itemImpl.length} |
| No battle effect in the sim (marked "— không tác dụng" in the picker) | ${itemNo.length} |

Simulated: ${itemImpl.map((i) => i.name).join(", ")}.

No effect in sim: ${itemNo.map((i) => i.name).join(", ")}.

## Rules notes
- Modern (Gen 5+) damage formula; rounding follows the cartridge (random roll floors, every later modifier rounds half down). Modifiers use 4096-based fixed point (Life Orb 5324/4096, 1.2x items 4915/4096, 1.1x items 4505/4096).
- Crit 1.5x at stage 0 = 1/24; high-crit moves +1 stage, Scope Lens / Razor Claw +1, Focus Energy +2.
- Sleep lasts 1-3 turns lost; freeze thaws 20% per turn; paralysis halves speed and fails 25%; confusion lasts 2-5 actions, 33% self-hit (40 power); burn 1/16, poison 1/8, toxic N/16.
- No weather, no terrain, no switching: abilities / items that depend on those do nothing.
`;
writeFileSync(path.join(root, "docs", "coverage.md"), md);
console.log({ moves: moves.length, full, partial: partial.length, noop: noop.length, abilities: { total: abilKeys.length, usedBySpecies: usedList.length, implUsed: abilImplUsed.length, noUsed: abilNoUsed.length, implTable: ABILITY_IMPL.size }, items: { total: items.length, impl: itemImpl.length, none: itemNo.length } });
